#!/usr/bin/env node
// Builds content/globeRegions.ts: the province or state (ISO 3166-2 code) of every land dot in
// content/globeLand.ts, so /places can shade the regions you have been to. Run by hand after
// make-globe-land.mjs; never at build or run time.
//
//   node scripts/make-globe-regions.mjs path/to/ne_10m_admin_1_states_provinces.geojson
//
// Input: Natural Earth 1:10m admin-1 states and provinces (public domain), from
// https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_10m_admin_1_states_provinces.geojson
// (41 MB; not committed). Dots just outside every region because of coastline generalisation take
// the region of the nearest tagged dot within 2.5 degrees.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { geoBounds, geoContains } from "d3-geo";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const input = process.argv[2];
if (!input) throw new Error("usage: make-globe-regions.mjs ne_10m_admin_1_states_provinces.geojson");

const landSource = readFileSync(join(root, "content/globeLand.ts"), "utf8");
const n = Number(/LATTICE_SIZE = (\d+)/.exec(landSource)[1]);
const runs = /LAND_RUNS = "([^"]+)"/.exec(landSource)[1];

const GOLDEN_ANGLE = Math.PI * (3 - Math.sqrt(5));
const latticePoint = (i) => [(((i * GOLDEN_ANGLE) % (2 * Math.PI)) * 180) / Math.PI - 180, (Math.asin(1 - (2 * i + 1) / n) * 180) / Math.PI];
const landIndices = [];
{
  let i = 0;
  let land = false;
  for (const part of runs.split(",")) {
    const length = Number(part);
    if (land) for (let k = 0; k < length; k++) landIndices.push(i + k);
    i += length;
    land = !land;
  }
}

const regions = JSON.parse(readFileSync(input, "utf8"))
  .features.filter((f) => f.geometry && /^[A-Z]{2}-[A-Z0-9]{1,3}$/.test(f.properties.iso_3166_2 ?? ""))
  .map((f) => ({ code: f.properties.iso_3166_2, feature: f, bounds: geoBounds(f) }));

const inBounds = ([lon, lat], [[w, s], [e, n2]]) => lat >= s - 0.5 && lat <= n2 + 0.5 && (w <= e ? lon >= w - 0.5 && lon <= e + 0.5 : lon >= w - 0.5 || lon <= e + 0.5);

const points = landIndices.map((i) => latticePoint(i));
const codes = points.map((p) => regions.find((r) => inBounds(p, r.bounds) && geoContains(r.feature, p))?.code ?? null);
const tagged = codes.filter(Boolean).length;

// Fill gaps along coasts from the nearest tagged dot.
const vec = ([lon, lat]) => {
  const a = (lat * Math.PI) / 180;
  const o = (lon * Math.PI) / 180;
  return [Math.cos(a) * Math.sin(o), Math.sin(a), Math.cos(a) * Math.cos(o)];
};
const vecs = points.map(vec);
const near = Math.cos((2.5 * Math.PI) / 180);
const filled = codes.map((code, k) => {
  if (code) return code;
  let best = null;
  let bestDot = near;
  codes.forEach((c, j) => {
    if (!c) return;
    const d = vecs[k][0] * vecs[j][0] + vecs[k][1] * vecs[j][1] + vecs[k][2] * vecs[j][2];
    if (d > bestDot) {
      bestDot = d;
      best = c;
    }
  });
  return best;
});

const table = [...new Set(filled.filter(Boolean))].sort();
const index = new Map(table.map((c, i) => [c, i]));
writeFileSync(
  join(root, "content/globeRegions.ts"),
  `// Generated by scripts/make-globe-regions.mjs from Natural Earth 1:10m admin-1 (public domain). Do not edit.

/** ISO 3166-2 codes of the provinces and states that contain at least one land dot. */
export const REGION_CODES: string[] = ${JSON.stringify(table)};

/** For each land dot of content/globeLand.ts, in order: its index in REGION_CODES (base 36), empty when none. */
export const DOT_REGIONS = "${filled.map((c) => (c ? index.get(c).toString(36) : "")).join(",")}";
`,
);
console.log(`${points.length} land dots: ${tagged} inside a region, ${filled.filter(Boolean).length - tagged} filled from neighbours, ${filled.filter((c) => !c).length} untagged; ${table.length} regions`);
