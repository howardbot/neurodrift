#!/usr/bin/env node
// Builds content/globeLand.ts: which points of an even (Fibonacci) lattice over the sphere fall on
// land, for the dotted globe on /places. Run by hand when the resolution should change; never at
// build or run time.
//
//   node scripts/make-globe-land.mjs [lattice size, default 18000]
//
// Land outlines: Natural Earth 1:50m (public domain) via the world-atlas package.
// The lattice formula must match latticePoint() in lib/globe.ts; the file records sample points
// that lib/globe.test.ts checks against it.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const n = Number(process.argv[2] ?? 18000);
const topo = JSON.parse(readFileSync(join(root, "node_modules/world-atlas/land-50m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

const GOLDEN_ANGLE = Math.PI * (3 - Math.sqrt(5));
const latticePoint = (i) => [(((i * GOLDEN_ANGLE) % (2 * Math.PI)) * 180) / Math.PI - 180, (Math.asin(1 - (2 * i + 1) / n) * 180) / Math.PI];

// Alternating run lengths, sea first: compact and quick to decode.
const runs = [];
let current = false;
let length = 0;
const landIndices = [];
for (let i = 0; i < n; i++) {
  const isLand = geoContains(land, latticePoint(i));
  if (isLand) landIndices.push(i);
  if (isLand === current) length++;
  else {
    runs.push(length);
    current = isLand;
    length = 1;
  }
}
runs.push(length);

const samples = [0, Math.floor(landIndices.length / 2), landIndices.length - 1].map((k) => {
  const i = landIndices[k];
  const [lon, lat] = latticePoint(i);
  return `[${i}, ${lon.toFixed(9)}, ${lat.toFixed(9)}]`;
});

writeFileSync(
  join(root, "content/globeLand.ts"),
  `// Generated by scripts/make-globe-land.mjs from Natural Earth 1:50m land (public domain). Do not edit.

/** Number of points in the Fibonacci lattice over the sphere. */
export const LATTICE_SIZE = ${n};

/** Alternating run lengths over the lattice, starting with sea: ${landIndices.length} land points. */
export const LAND_RUNS = "${runs.join(",")}";

/** Sample land points [index, lon, lat] for checking lib/globe.ts uses the same lattice. */
export const LAND_SAMPLES: [number, number, number][] = [${samples.join(", ")}];
`,
);
console.log(`${landIndices.length} of ${n} lattice points are land (${((100 * landIndices.length) / n).toFixed(1)}%), ${runs.length} runs`);
